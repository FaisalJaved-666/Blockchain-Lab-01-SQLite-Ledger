import sqlite3
import csv
import pandas as pd
from google.colab import files

# Step 1: Create SQLite database
con = sqlite3.connect('week01_ledger.sqlite')

con.execute('DROP TABLE IF EXISTS events')

con.execute('''
CREATE TABLE events (
    seq INTEGER PRIMARY KEY,
    event TEXT NOT NULL,
    approved_by TEXT NOT NULL
)
''')

# Step 2: Insert four certificate records
records = [
    ('Issue certificate C-001', 'Registrar'),
    ('Issue certificate C-002', 'Registrar'),
    ('Revoke certificate C-001', 'Registrar'),
    ('Issue certificate C-003', 'Registrar')
]

con.executemany(
    'INSERT INTO events(event, approved_by) VALUES(?, ?)',
    records
)
con.commit()

# Step 3: Read SQLite records
rows = con.execute(
    'SELECT seq, event, approved_by FROM events ORDER BY seq'
).fetchall()

print("CENTRAL DATABASE (SQLite):")
for row in rows:
    print(row)

# Step 4: Create CSV file
csv_filename = 'week01_ledger.csv'

with open(csv_filename, 'w', newline='', encoding='utf-8') as output:
    writer = csv.writer(output)
    writer.writerow(['seq', 'event', 'approved_by'])
    writer.writerows(rows)

# Step 5: Display CSV as a table
df = pd.read_csv(csv_filename)

print("\nCSV FILE DATA:")
display(df)

# Step 6: Simulate conflicting copies
registrar_copy = list(rows)
employer_copy = list(rows)

employer_copy[1] = (
    employer_copy[1][0],
    'Issue certificate C-999',
    employer_copy[1][2]
)

print("\nSHARED-COPY EXPERIMENT:")

for a, b in zip(registrar_copy, employer_copy):
    if a != b:
        print("CONFLICT DETECTED:", a, "versus", b)

print("\nAudit question: WHO is authorized to decide the correct record?")

assert len(rows) == 4 and registrar_copy != employer_copy

print("PASS: central ledger stored; independently modified copies disagree.")

con.close()

